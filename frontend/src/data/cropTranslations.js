export const getLocalizedCropName = (cropKey, lang = 'en') => {
  if (!cropKey) return 'Crop';
  const crop = CROP_TRANSLATIONS[cropKey.toLowerCase()];
  if (crop && crop[lang]) {
    return crop[lang];
  }
  return cropKey.charAt(0).toUpperCase() + cropKey.slice(1);
};
